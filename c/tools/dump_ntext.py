import json, os, random, sys, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)


def tables():
    out = ["/* generated by tools/dump_ntext.py --tables: NFKD + ascii-ignore of each non-ASCII code point (rescorer.norm)"
           " */", "static const struct { uint32_t cp; const char* s; } NFKD_ASCII[] = {"]
    row = []
    for c in range(0x80, 0x110000):
        s = unicodedata.normalize('NFKD', chr(c)).encode('ascii', 'ignore').decode()
        if s:
            row.append('{0x%X, %s}' % (c, json.dumps(s)))
            if len(row) == 6:
                out.append('    ' + ', '.join(row) + ',')
                row = []
    if row:
        out.append('    ' + ', '.join(row) + ',')
    out.append('};')
    out.append('/* str.isupper() of one code point, as ranges */')
    out.append('static const uint32_t UPPER[][2] = {')
    r, prev = [], False
    for c in range(0x80, 0x110000):
        x = chr(c).isupper()
        if x and not prev:
            r.append([c, c])
        elif x:
            r[-1][1] = c
        prev = x
    for i in range(0, len(r), 8):
        out.append('    ' + ', '.join('{0x%X, 0x%X}' % (a, b) for a, b in r[i:i + 8]) + ',')
    out.append('};')
    out.append('/* non-ASCII code points whose str.lower() has ASCII letters (the rest of it written as \\x01) */')
    out.append('static const struct { uint32_t cp; const char* s; } LOWER_ASCII[] = {')
    for c in range(0x80, 0x110000):
        lo = chr(c).lower()
        if any(ord(ch) < 128 for ch in lo):
            out.append('    {0x%X, %s},' % (c, json.dumps(''.join(ch if ord(ch) < 128 else '\x01' for ch in lo)).replace('\\u0001', '\\001')))
    out.append('};')
    print('\n'.join(out))


def main():
    if '--tables' in sys.argv:
        return tables()
    import numpy as np
    import jellyfish, difflib
    from arc_audio import rescorer as RS, namesim as NS, kbsnap as KS
    from arc_audio.textlayer import ExactNames, is_cap
    args = [a for a in sys.argv[1:] if not a.startswith('-')]
    cfg = json.load(open(args[0])) if args else None
    rnd = random.Random(1)
    W = lambda d: print(json.dumps(d, ensure_ascii=False))

    ex = json.load(open(os.path.join(ROOT, 'examples', 'example_names.json')))
    kb2 = ex + [
        dict(name='José Álvarez-Núñez', kind='person', group='Riverside Comets', aliases=['Jose Alvarez', 'Álvarez']),
        dict(name="Liam O'Connor Jr.", kind='person', group='Harbor City Hawks'),
        dict(name='Zoë Kravitz', kind='person'), dict(name='Søren Kierkegaard', kind='person', aliases=['Kierkegaard']),
        dict(name='Björn Borg', kind='person'), dict(name='Phil Knight', kind='person', group='Riverside Comets'),
        dict(name='Christopher Wright', kind='person', aliases=['Chris Wright', 'C.J.']),
        dict(name='Thompson', kind='person'), dict(name='Ethan Thompson', kind='person', group='Riverside Comets'),
        dict(name='Mia Thompson', kind='person'), dict(name='Riverside Arena', kind='place'),
        dict(name='Acme Corp', kind='organization', aliases=['Acme']), dict(name='Telegram', kind='other'),
        dict(name='Ganymede', kind='game_map'), dict(name='Xavier Schmidt', kind='person', aliases=['X']),
        dict(name='Harbor City Hawks Reserves', kind='team', group='Harbor City Hawks'),
    ]
    # ---- normalisers, case, metaphone, phon
    strs = ["Marcus Delaney's", "O'Brien's dog", "it's", "Jean-Luc Picard", "José Álvarez-Núñez", "Zoë", "Søren", "ß",
            "æon", "ﬁnal", "Ⅻ", "½ time", "İstanbul", "Kelvin K", "naïve café", "Ångström", "ŁÓDŹ", "Đorđe", "Œuvre",
            "  spaced\tout  ", "UPPER CASE", "a's b's", "'s", "x's_y", "ÿ", "Mötley Crüe", "Nguyễn Văn", "Ｆｕｌｌ", "№ 5",
            "", "it’s", "under_score", "tab\there", "Ünal", "ǅemal", "x²", "Ⓐ", "dash–em—", "Ⅳ", "ı", "Ǆ"]
    for n in kb2:
        strs.append(n['name'])
        strs += n.get('aliases', [])
    for s in strs:
        W(dict(k='norm', i=s, norm=RS.norm(s), snorm=NS.norm(s), nrm=KS.nrm(s), cap=is_cap(s), up=s[:1].isupper()))
    words = sorted({l.strip() for l in open('/usr/share/dict/words')}) if os.path.exists('/usr/share/dict/words') else []
    sample = rnd.sample(words, min(1800, len(words))) if words else []
    extra = ['knight', 'gnome', 'wright', 'aesop', 'xavier', 'xhosa', 'whale', 'ghost', 'sugar', 'dodge', 'thumb', 'sign',
             'science', 'schmidt', 'caesar', 'phil', 'zz', 'cc', 'ach', 'tia', 'tion', 'brandt', 'delaney', 'castellano',
             'harbor city hawks', 'b', 'mb', 'gh', 'high', 'hugh', 'tough', "o'brien", 'r2d2', '42', 'x', 'wh', 'what',
             'mc donald', 'jean-luc', 'cia', 'chia', 'sch', 'dgy', 'dge', 'ghana', 'gnat', 'tch', 'thth', 'xi', 'whh']
    for w in sample + extra:
        W(dict(k='meta', i=w, o=jellyfish.metaphone(w), ph=NS.phon(w.lower()), km=KS.metaphone(KS.nrm(w))))
    # ---- ratio (rapidfuzz) and difflib ratio
    pairs = [('', ''), ('', 'a'), ('abc', 'abc'), ('marcus delaney', 'marcus delany'), ('brandt', 'brant'),
             ('theo brandt', 'brandt'), ('harbor city hawks', 'harbour city hawks'), ('kitten', 'sitting')]
    for _ in range(200):
        a, b = rnd.choice(words or ['x']).lower(), rnd.choice(words or ['y']).lower()
        pairs.append((a, b))
        pairs.append((a, a[:-1] + 'e'))
    big = ''.join(rnd.choice('abcde ') for _ in range(260))
    pairs += [(big, big[::-1]), (big[:230] + 'zz', big), ('ab' * 120, 'ba' * 110), (big, 'abcde')]
    for a, b in pairs:
        W(dict(k='ratio', a=a, b=b, o=RS.ratio(a, b), sq=difflib.SequenceMatcher(None, a, b).ratio()))
    # ---- sim (rescorer)
    spans = ['marcus delaney', 'delany', 'brant', 'theo', 'hawks', 'harbour city', 'castelano', 'comets', 'jose alvarez',
             'alvarez nunez', 'kirkegard', 'chris right', 'tomson', 'acme', 'telegram', 'zoe', '', 'the', 'oconnor',
             'liam o connor', 'xavier smith', 'ganimede', 'riverside']
    for s in spans:
        for c in kb2:
            W(dict(k='sim', span=s, forms=sorted(RS.name_forms(c)), o=RS.sim(s, RS.name_forms(c))))
    # ---- sim_feats
    for names in ([c['name'] for c in ex], [c['name'] for c in kb2], ['Marcus Delaney'], []):
        sp = ['Delaney', 'Theo Brandt', 'brant', 'Harbor City', 'Castellano', 'xyz', '', 'Jose', 'the hawks',
              'Christopher', 'Thompson Mia', 'Søren', 'ab']
        ct = NS.CandTable(names)
        F = NS.sim_feats(sp, ct)
        W(dict(k='feats', names=names, spans=sp, o=[float(x) for x in F.astype(np.float32).reshape(-1)]))
    # ---- policy / rescorer params (engine._policy npol, engine._resc_params)
    rcfg = cfg['rescorer'] if cfg else None
    pcfg = cfg['name_policy'] if cfg else None
    if cfg:
        cases = []
        for ws in ('builtin', 'external', 'verbit'):
            for d in list(rcfg) + ['unknown', 'nonsense']:
                npc = pcfg.get(ws if ws in ('builtin', 'external') else 'external') or {}
                npol = dict(npc.get('*') or {}, **npc.get(d) or {})
                rp = dict(rcfg.get(d, rcfg['unknown']))
                if npol.get('delta') is not None:
                    rp['bias'] = float(rp.get('bias', 0.0)) + float(npol['delta'])
                if npol.get('thr') is not None:
                    rp['thr'] = float(npol['thr'])
                cases.append([d, ws, rp, npol])
        W(dict(k='policy', cfg=dict(rescorer=rcfg, name_policy=pcfg), cases=cases))
    # ---- rescorer
    psets = [dict(v, _d=d) for d, v in (rcfg or {}).items()] or [dict(A=10, A2=6, B=2, T=0, R=0, bias=1, thr=0.6)]
    psets += [dict(A=10, A2=10, B=4, T=4, R=4, bias=-6, thr=0.7), dict(A=0, A2=0, bias=0)]
    pasts = ['', 'the harbor city hawks lead the riverside comets', 'comets comets hawks', 'riverside riverside hawks',
             'and marcus delaney with the ball']
    for kb in (ex, kb2):
        for ps in (psets if kb is ex else psets[::3]):
            params = {k: v for k, v in ps.items() if not k.startswith('_') and k != 'weights_from'}
            r = RS.NameRescorer(kb, params)
            steps = []
            t = 0.0
            for _ in range(14):
                t += rnd.choice([0.5, 3.0, 40.0, 130.0])
                if rnd.random() < 0.15:
                    row = rnd.randrange(len(kb))
                    r.recent.append((t, row))
                    steps.append(dict(push=[t, row]))
                    continue
                R = len(kb)
                z = np.float32([rnd.gauss(0, 4) for _ in range(2 + R)])
                z[1] = -10000.0
                for k in range(2, 2 + R):
                    if rnd.random() < 0.3:
                        z[k] = -10000.0
                if rnd.random() < 0.5:
                    z[2 + rnd.randrange(R)] += 12
                allowed = sorted(rnd.sample(range(R), rnd.randint(0, R)))
                span = rnd.choice(spans)
                past = rnd.choice(pasts)
                feed = rnd.choice([None, '', 'Marcus Delaney scores for Harbor City', 'comets'])
                o = r.score(t, z, allowed, span, past, feed)
                steps.append(dict(t=t, z=[json.loads(str(x)) for x in z], allowed=allowed, span=span, past=past, feed=feed, o=o))
            W(dict(k='resc', kb=kb, params=params, steps=steps))
    # ---- ExactNames
    for kb in (ex, kb2):
        e = ExactNames(kb)
        texts = ['Marcus Delaney brings it up', 'Brandt to Delaney.', 'the hawks win', 'Harbor City Hawks Reserves',
                 'Thompson and Mia Thompson', 'jose alvarez scores', 'nothing here', 'Acme', 'theo brandt',
                 'Kierkegaard wrote', 'Phil Knight, Owen Castellano']
        ri = [[t, e.rows_in(t)] for t in texts]
        sp = []
        for t in texts + ['Delaney passes to Brandt , Brandt scores', 'Comets beat Hawks', 'castellano Castellano']:
            ws = t.split()
            sp.append([ws, None, [list(x) for x in e.spans(ws)]])
            used = [rnd.random() < 0.3 for _ in ws]
            sp.append([ws, used, [list(x) for x in e.spans(ws, used)]])
        W(dict(k='exact', kb=kb, empty=not bool(e), rows_in=ri, spans=sp, tag_of=[e.tag_of(r) for r in range(len(kb))]))
    # ---- kbsnap
    for kb in (ex, kb2, []):
        K = KS.KB(kb)
        sc = []
        for t in spans + ['Marcus Delaney', 'Hawks', 'Harbor City Hawks', 'Comets', "O'Connor", 'Jr', 'Delaney.',
                          'Theo Brandt', 'Thomson', 'Borg', 'Xavier Schmidt', 'Teo Brant']:
            s, nm, kd, ph = K.score(t)
            sc.append([t, s, nm, kd, ph])
        ln = []
        for t in ['Delaney', 'Brant', 'delaney', 'Hawks', 'xyz', 'Riverside', 'Thompsen']:
            for rec0 in (dict(heard=t), dict(heard=t, entity='X'), dict(heard=t, state='linked')):
                rec = dict(rec0)
                ok = KS.link(rec, K)
                ln.append([rec0, ok, rec.get('entity') if ok else None, rec.get('snap_score') if ok else None])
        adds = []
        utts = ['Delaney to Theo Brandt.', 'That puts the Harbor City Hawks ahead 102 to 98.',
                'Brandt drives, he scores. What a move by Theo Brandt.', 'the comets and The Comets and Riverside Comets',
                'Zoë Kravitz met Björn Borg', 'Xavier Schmidt and Acme Corp', 'Owen Castellano Owen castellano']
        for u in utts:
            t0 = rnd.random() * 10
            ws = []
            for w in u.split():
                ws.append(dict(text=w, start=round(t0, 2), end=round(t0 + 0.3, 2)))
                t0 += 0.35
            if rnd.random() < 0.5:
                ws[0]['tag'] = 'ENTITY_PERSON'
            if rnd.random() < 0.3:
                ws[1]['text'] = ''
            names = []
            if rnd.random() < 0.5:
                names.append(dict(start=ws[2]['start'], end=ws[3]['end']))
            n = [0]

            def nid():
                n[0] += 1
                return 'nm%d' % n[0]
            out = KS.add_spans(ws, names, K, nid)
            adds.append(dict(words=ws, names=[[r['start'], r['end']] for r in names], out=out))
        W(dict(k='snap', kb=kb, score=sc, link=ln, add=adds))


if __name__ == '__main__':
    main()
